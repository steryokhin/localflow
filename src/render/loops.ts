// Generated views over loops.md: the board (ACTIONS.md), what needs a nudge now (NUDGES.md), and
// the standup summary. Pure functions of the loops, the tickets and the clock.

import fs from "node:fs";
import path from "node:path";
import { compareKeys } from "../jira/mapping.ts";
import { readTextIfExists, writeFileAtomic } from "../util.ts";
import { dueAt, fmtDay, ME, LOOPS_ARCHIVE } from "../vault/loops.ts";
import type { Loop } from "../vault/loops.ts";
import { isTracked, readLog, readLogLines } from "../vault/notes.ts";
import type { LogLine } from "../vault/notes.ts";
import { NOTES_FILE } from "../vault/store.ts";
import type { Ticket } from "../vault/store.ts";

export const ACTIONS_FILE = "ACTIONS.md";
export const NUDGES_FILE = "NUDGES.md";
/** A loop that expires within this window is "soon". */
export const SOON_MS = 60 * 60 * 1000;
const PLAN_FILE = "actions.md";
const CLOSED = ["done", "archived"];

const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
const pad = (n: number): string => String(n).padStart(2, "0");
const sameDay = (a: Date, b: Date): boolean => fmtDay(a) === fmtDay(b);
const endOfDay = (d: Date): Date => new Date(d.getFullYear(), d.getMonth(), d.getDate(), 23, 59, 59, 999);
const dayName = (d: Date): string => `${DAYS[d.getDay()]} ${d.getDate()} ${MONTHS[d.getMonth()]}`;

/** "18:00" today, "13 Oct 12:00", "15 Oct" (date-only deadline). */
export function fmtDue(due: string, now: Date): string {
  const at = dueAt(due);
  if (!at) return due || "no deadline";
  const dateOnly = !due.includes(" ");
  if (sameDay(at, now)) return dateOnly ? "today" : `${pad(at.getHours())}:${pad(at.getMinutes())}`;
  const day = `${at.getDate()} ${MONTHS[at.getMonth()]}`;
  return dateOnly ? day : `${day} ${pad(at.getHours())}:${pad(at.getMinutes())}`;
}

/** "40m", "5h", "2d". */
export function fmtSpan(ms: number): string {
  const m = Math.max(0, Math.round(ms / 60_000));
  if (m < 60) return `${m}m`;
  if (m < 48 * 60) return `${Math.round(m / 60)}h`;
  return `${Math.round(m / 1440)}d`;
}

export interface Buckets {
  expired: Loop[];
  today: Loop[];
  waiting: Loop[];
  mine: Loop[];
}

const byDue = (a: Loop, b: Loop): number => (dueAt(a.due)?.getTime() ?? Infinity) - (dueAt(b.due)?.getTime() ?? Infinity);

/** Expired first ("eat the frog"), then due today, then the rest split by who owes the next move. */
export function bucket(loops: Loop[], now: Date): Buckets {
  const out: Buckets = { expired: [], today: [], waiting: [], mine: [] };
  for (const l of [...loops].sort(byDue)) {
    const at = dueAt(l.due);
    if (at && at <= now) out.expired.push(l);
    else if (at && at <= endOfDay(now)) out.today.push(l);
    else if (l.owner !== ME) out.waiting.push(l);
    else out.mine.push(l);
  }
  return out;
}

function who(l: Loop): string {
  return l.owner === ME ? "" : ` · from ${l.owner}`;
}

function loopLine(l: Loop, now: Date, opts: { overdue?: boolean } = {}): string {
  const at = dueAt(l.due);
  const when = opts.overdue && at ? `was due ${fmtDue(l.due, now)}, ${fmtSpan(now.getTime() - at.getTime())} ago` : `by ${fmtDue(l.due, now)}`;
  return `- ${l.id} · ${l.key ?? "—"} · ${l.text}${who(l)} · ${when}${l.onExpiry ? ` · else: ${l.onExpiry}` : ""}`;
}

/** Unchecked "- [ ]" items in the ticket's actions.md: the ticket has a plan of its own. */
function hasPlan(t: Ticket): boolean {
  const text = readTextIfExists(path.join(t.dir, PLAN_FILE));
  return !!text && /^\s*- \[ \]/m.test(text);
}

function lastLog(t: Ticket): string | null {
  const log = readLog(readTextIfExists(path.join(t.dir, NOTES_FILE)) ?? "");
  return log.length ? log[log.length - 1].date : null;
}

/** Tracked, still-open tickets with neither an open loop nor a plan: candidates for `lf untrack`. */
export function idleTickets(tickets: Ticket[], loops: Loop[]): Ticket[] {
  const withLoops = new Set(loops.map((l) => l.key).filter(Boolean));
  return tickets.filter((t) => isTracked(t) && !CLOSED.includes(t.status) && !withLoops.has(t.key) && !hasPlan(t));
}

export function renderActions(loops: Loop[], tickets: Ticket[], now: Date): string {
  const b = bucket(loops, now);
  const lines = [
    `# Loops — ${dayName(now)} ${now.getFullYear()}, ${pad(now.getHours())}:${pad(now.getMinutes())}`,
    "",
    "_Generated by `lf`. Do not edit: loops live in loops.md._",
    "",
  ];
  const section = (title: string, items: string[], empty?: string): void => {
    if (!items.length && !empty) return;
    lines.push(`## ${title} (${items.length})`, "", ...(items.length ? items : [`_${empty}_`]), "");
  };
  section("🐸 Expired", b.expired.map((l) => loopLine(l, now, { overdue: true })), "Nothing expired — no frog today.");
  section("⏰ Due today", b.today.map((l) => loopLine(l, now)));
  section("🟡 Waiting on people", b.waiting.map((l) => loopLine(l, now)));
  section("⚪ Mine", b.mine.map((l) => loopLine(l, now)));
  const idle = idleTickets(tickets, loops).map((t) => {
    const last = lastLog(t);
    return `- ${t.key} · ${t.title} · ${last ? `last log ${last}` : "nothing logged"} → \`lf loop … --key ${t.key}\` or \`lf untrack ${t.key}\``;
  });
  section("❓ Tracked tickets without loops or a plan", idle);
  if (!loops.length) lines.push("_No open loops. Add one with `lf loop \"what I am waiting for\" --by +4h --key KEY`._", "");
  return lines.join("\n").trimEnd() + "\n";
}

export interface Nudges {
  expired: Loop[];
  soon: Loop[];
}

export function nudges(loops: Loop[], now: Date): Nudges {
  const at = (l: Loop): number => dueAt(l.due)?.getTime() ?? Infinity;
  const sorted = [...loops].sort(byDue);
  return {
    expired: sorted.filter((l) => at(l) <= now.getTime()),
    soon: sorted.filter((l) => at(l) > now.getTime() && at(l) <= now.getTime() + SOON_MS),
  };
}

export function renderNudges(n: Nudges, now: Date): string {
  const lines = [`# Nudges — ${dayName(now)}, ${pad(now.getHours())}:${pad(now.getMinutes())}`, "", "_Generated by `lf watch`. Act on these, then `lf done`, `lf bump` or `lf loop`._", ""];
  if (!n.expired.length && !n.soon.length) lines.push("Nothing is due within the hour.");
  if (n.expired.length) lines.push(`## Expired (${n.expired.length})`, "", ...n.expired.map((l) => loopLine(l, now, { overdue: true })), "");
  if (n.soon.length) lines.push(`## Within the hour (${n.soon.length})`, "", ...n.soon.map((l) => loopLine(l, now)), "");
  return lines.join("\n").trimEnd() + "\n";
}

/** Short text for a desktop notification. */
export function nudgeMessage(fresh: Nudges): string {
  const part = (l: Loop): string => `${l.owner === ME ? "" : `${l.owner}: `}${l.text}${l.key ? ` (${l.key})` : ""}`;
  return [
    ...fresh.expired.map((l) => `Expired — ${part(l)}`),
    ...fresh.soon.map((l) => `Soon — ${part(l)}`),
  ].join("\n");
}

/** Generated files stay out of the vault's git: they are rewritten all the time. */
export function ensureIgnored(vault: string, names: string[]): void {
  const file = path.join(vault, ".gitignore");
  const text = readTextIfExists(file) ?? "";
  const have = new Set(text.split("\n").map((l) => l.trim()));
  const missing = names.filter((n) => !have.has(n));
  if (missing.length && fs.existsSync(vault)) writeFileAtomic(file, `${text.replace(/\n*$/, text ? "\n" : "")}${missing.join("\n")}\n`);
}

// ---------- standup ----------

/** The previous working day (Friday when today is Monday or the weekend). */
export function lastWorkingDay(now: Date): Date {
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 1);
  while (d.getDay() === 0 || d.getDay() === 6) d.setDate(d.getDate() - 1);
  return d;
}

interface Logged extends LogLine {
  key: string | null;
}

function allLogs(vault: string, tickets: Ticket[]): Logged[] {
  const out: Logged[] = [];
  for (const t of tickets) {
    for (const l of readLog(readTextIfExists(path.join(t.dir, NOTES_FILE)) ?? "")) out.push({ ...l, key: t.key });
  }
  for (const l of readLogLines(readTextIfExists(path.join(vault, LOOPS_ARCHIVE)) ?? "")) out.push({ ...l, key: null });
  return out.sort((a, b) => `${a.date} ${a.time}`.localeCompare(`${b.date} ${b.time}`));
}

export function renderStandup(vault: string, loops: Loop[], tickets: Ticket[], now: Date, week: boolean): string {
  const from = week ? new Date(now.getFullYear(), now.getMonth(), now.getDate() - 7) : lastWorkingDay(now);
  const since = fmtDay(from);
  const logs = allLogs(vault, tickets).filter((l) => l.date >= since);
  const lines = [`${week ? "Week" : "Standup"} — ${dayName(now)}`, ""];

  lines.push(week ? `Done since ${dayName(from)}:` : `Done (since ${dayName(from)}):`);
  if (!logs.length) lines.push("- nothing logged");
  if (week) {
    const byKey = new Map<string, Logged[]>();
    for (const l of logs) byKey.set(l.key ?? "—", [...(byKey.get(l.key ?? "—") ?? []), l]);
    const title = new Map(tickets.map((t) => [t.key, t.title]));
    for (const key of [...byKey.keys()].sort((a, b) => (a === "—" ? 1 : b === "—" ? -1 : compareKeys(a, b)))) {
      lines.push(`- ${key === "—" ? "No ticket" : `${key} ${title.get(key) ?? ""}`.trim()}`);
      for (const l of byKey.get(key)!) lines.push(`    - ${l.date.slice(5)} ${l.text}`);
    }
  } else {
    for (const l of logs) lines.push(`- ${l.key ? `${l.key}: ` : ""}${l.text}`);
  }

  const at = (l: Loop): number => dueAt(l.due)?.getTime() ?? Infinity;
  const opened = (l: Loop): string => {
    const c = dueAt(l.created);
    return c ? `, waiting ${fmtSpan(now.getTime() - c.getTime())}` : "";
  };
  const ref = (l: Loop): string => (l.key ? ` (${l.key})` : "");
  const mineToday = loops.filter((l) => l.owner === ME && at(l) <= endOfDay(now).getTime()).sort(byDue);
  const theirs = loops.filter((l) => l.owner !== ME).sort(byDue);
  const blocked = theirs.filter((l) => at(l) <= now.getTime());
  const waiting = theirs.filter((l) => at(l) > now.getTime());

  lines.push("", "Doing today:");
  if (!mineToday.length) lines.push("- no loops of mine due today");
  for (const l of mineToday) lines.push(`- ${l.text}${ref(l)} — ${at(l) <= now.getTime() ? "overdue" : `by ${fmtDue(l.due, now)}`}`);
  lines.push("", "Waiting on:");
  if (!waiting.length) lines.push("- nobody");
  for (const l of waiting) lines.push(`- ${l.owner}: ${l.text}${ref(l)} — due ${fmtDue(l.due, now)}${opened(l)}`);
  lines.push("", "Blockers:");
  if (!blocked.length) lines.push("- none");
  for (const l of blocked) lines.push(`- ${l.owner}: ${l.text}${ref(l)} — overdue ${fmtSpan(now.getTime() - at(l))}${opened(l)}`);
  return lines.join("\n") + "\n";
}
